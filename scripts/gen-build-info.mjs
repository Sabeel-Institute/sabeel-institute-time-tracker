// Generate app/src/build-info.ts with the app version + short git commit, so the
// sign-in screen can show exactly which build is running. Run at BUILD time (wired
// into `prepare`, `web:export`, and the APK release) so the commit is the one
// actually shipped. (Ported from the sibling kanban app.)
//
// The release (scripts/release.mjs --ship) runs this on main's merged release
// commit, so both the APK build and the later `firebase deploy` web build stamp
// the same commit — the sign-in footer then matches on every surface.
import { readFileSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const version = JSON.parse(readFileSync(resolve(root, 'app/app.json'), 'utf8')).expo.version;

let commit = 'dev';
try {
  commit = execSync('git rev-parse --short HEAD', { cwd: root }).toString().trim();
  const dirty = execSync('git status --porcelain', { cwd: root }).toString().trim();
  if (dirty) commit += '+';
} catch {
  // Not a git checkout (or git missing) — leave "dev".
}

const body = `// GENERATED by scripts/gen-build-info.mjs — do not edit by hand.
// Regenerated at every build (prepare + web export + APK release). The '+' suffix
// means the build was cut with uncommitted changes.
export const BUILD_INFO = { version: '${version}', commit: '${commit}' } as const;
`;
writeFileSync(resolve(root, 'app/src/build-info.ts'), body);
console.log(`build-info.ts → v${version} · ${commit}`);
